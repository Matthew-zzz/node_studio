import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { basename, extname } from "node:path";
import sharp from "sharp";
import { screenshots } from "../src/features/projects/data/screenshots.ts";

const root = new URL("../", import.meta.url);
const output = new URL("public/assets/screenshots/", root);
const sources = new Map(Object.values(screenshots).flatMap((image) => [image, image.mobile].filter(Boolean)).map((image) => [image.src, image]));
const manifest = {};
const report = [];
await mkdir(output, { recursive: true });

for (const [src, image] of sources) {
  const original = await readFile(new URL(`public${src}`, root));
  const metadata = await sharp(original).metadata();
  if (metadata.width !== image.width || metadata.height !== image.height) throw new Error(`Incorrect source dimensions: ${src}`);
  const widths = [...new Set([320, 480, 640, 768, 1024, 1280, metadata.width])].filter((width) => width <= metadata.width).sort((a, b) => a - b);
  // The parent directory distinguishes a portrait mobile source from a desktop source.
  const name = src.slice("/assets/".length).replaceAll("/", "-").slice(0, -extname(src).length);
  const quality = metadata.format === "jpeg" ? 82 : 90;
  const variants = [];
  for (const width of widths) {
    const file = `${name}-${width}.webp`;
    const { data, info } = await sharp(original)
      .resize({ width, withoutEnlargement: true })
      .webp({ quality, effort: 6, smartSubsample: true })
      .toBuffer({ resolveWithObject: true });
    await writeFile(new URL(file, output), data);
    variants.push({ src: `/assets/screenshots/${file}`, width: info.width, height: info.height, bytes: data.length });
  }
  manifest[src] = { srcSet: variants.map((variant) => `${variant.src} ${variant.width}w`).join(", ") };
  report.push({ source: src, sha256: createHash("sha256").update(original).digest("hex"), bytes: original.length, width: image.width, height: image.height, quality, variants });
  console.log(`${basename(src)}: ${(original.length / 1024).toFixed(0)} → ${(variants.at(-1).bytes / 1024).toFixed(0)} KiB (${variants.length} sizes)`);
}

await writeFile(new URL("src/features/projects/data/responsive-screenshots.ts", root), `// Generated by npm run assets:screenshots.\nexport const responsiveScreenshots: Readonly<Record<string, { readonly srcSet: string }>> = ${JSON.stringify(manifest, null, 2)};\n`);
await writeFile(new URL("docs/asset-generation/project-screenshots.json", root), JSON.stringify({ command: "npm run assets:screenshots", images: report }, null, 2) + "\n");
