import { mkdir, readFile, writeFile } from "node:fs/promises";
import sharp from "sharp";

const projects = [
  { id: "vectra", source: "vectra-showcase.png" },
  { id: "autoparts", source: "autoparts-showcase.png" },
  { id: "animeLove", source: "animelove-showcase.png" },
];
const outputDirectory = new URL("../public/assets/showcase/", import.meta.url);
const manifest = {};
await mkdir(outputDirectory, { recursive: true });

for (const project of projects) {
  const original = await readFile(new URL(`../public/assets/${project.source}`, import.meta.url));
  const metadata = await sharp(original).metadata();
  if (!metadata.width || !metadata.height) throw new Error(`Missing dimensions: ${project.source}`);
  const widths = [...new Set([480, 640, 768, 1024, metadata.width])]
    .filter((width) => width <= metadata.width)
    .sort((a, b) => a - b);
  const variants = [];

  for (const width of widths) {
    const filename = `${project.id}-${width}.webp`;
    const buffer = await sharp(original)
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: 90, effort: 6, smartSubsample: true })
      .toBuffer();
    await writeFile(new URL(filename, outputDirectory), buffer);
    variants.push(`/assets/showcase/${filename} ${width}w`);
    console.log(`${filename}: ${(buffer.length / 1024).toFixed(1)} KiB`);
  }

  manifest[project.id] = {
    fallback: `/assets/${project.source}`,
    srcSet: variants.join(", "),
    width: metadata.width,
    height: metadata.height,
  };
}

const destination = new URL("../src/features/projects/data/showcase-images.ts", import.meta.url);
await writeFile(destination, `// Generated by npm run assets:showcases.\nexport const showcaseImages = ${JSON.stringify(manifest, null, 2)} as const;\n`);
